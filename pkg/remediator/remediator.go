// Remediator generates Ansible remediation playbooks
type Remediator struct {
	deploymentMethod string
	outputDir        string
}

// New creates a new Remediator
func New(deploymentMethod, outputDir string) *Remediator {
	return &Remediator{
		deploymentMethod: deploymentMethod,
		outputDir:        outputDir,
	}
}

// Generate creates Ansible remediation for failed findings
func (r *Remediator) Generate(result *models.ScanResult) error {
	// Filter to only failed findings
	var failedFindings []models.Finding
	for _, f := range result.Findings {
		if f.Status == models.StatusFail {
			failedFindings = append(failedFindings, f)
		}
	}

	if len(failedFindings) == 0 {
		fmt.Println("No failed findings to remediate")
		return nil
	}

	fmt.Printf("Generating remediation for %d failed controls\n", len(failedFindings))

	// Create output directory structure
	roleDir := filepath.Join(r.outputDir, "roles", "stig-remediation")
	if err := os.MkdirAll(filepath.Join(roleDir, "tasks"), 0750); err != nil {
		return fmt.Errorf("failed to create role directory: %w", err)
	}
	if err := os.MkdirAll(filepath.Join(roleDir, "templates"), 0750); err != nil {
		return fmt.Errorf("failed to create templates directory: %w", err)
	}
	if err := os.MkdirAll(filepath.Join(roleDir, "defaults"), 0750); err != nil {
		return fmt.Errorf("failed to create defaults directory: %w", err)
	}
	if err := os.MkdirAll(filepath.Join(roleDir, "handlers"), 0750); err != nil {
		return fmt.Errorf("failed to create handlers directory: %w", err)
	}

	// Generate main playbook
	if err := r.generatePlaybook(); err != nil {
		return fmt.Errorf("failed to generate playbook: %w", err)
	}

	// Generate inventory template
	if err := r.generateInventory(); err != nil {
		return fmt.Errorf("failed to generate inventory: %w", err)
	}

	// Generate role files
	if err := r.generateMainTasks(failedFindings); err != nil {
		return fmt.Errorf("failed to generate tasks: %w", err)
	}

	if err := r.generateHandlers(); err != nil {
		return fmt.Errorf("failed to generate handlers: %w", err)
	}

	if err := r.generateDefaults(); err != nil {
		return fmt.Errorf("failed to generate defaults: %w", err)
	}

	// Generate STIG mapping file
	if err := r.generateSTIGMapping(failedFindings); err != nil {
		return fmt.Errorf("failed to generate STIG mapping: %w", err)
	}

	fmt.Printf("Remediation playbook generated at: %s\n", r.outputDir)
	return nil
}

func (r *Remediator) generatePlaybook() error {
	playbook := `---
# StigKube Remediation Playbook
# Generated for deployment method: ` + r.deploymentMethod + `
#
# IMPORTANT: Review all changes before applying!
# Run with --check first: ansible-playbook -i inventory site.yml --check

- name: Apply STIG remediation to Kubernetes cluster
  hosts: control_plane
  become: yes
  gather_facts: yes

  pre_tasks:
    - name: Verify Kubernetes is running
      command: kubectl get nodes
      register: kubectl_check
      changed_when: false
      failed_when: kubectl_check.rc != 0

    - name: Backup current configurations
      archive:
        path:
          - /etc/kubernetes/manifests
          - /var/lib/kubelet/config.yaml
        dest: "/root/k8s-backup-{{ ansible_date_time.iso8601_basic_short }}.tar.gz"
      when: stig_backup_configs | default(true)

  roles:
    - stig-remediation

  post_tasks:
    - name: Wait for API server to be ready
      command: kubectl get nodes
      register: result
      until: result.rc == 0
      retries: 30
      delay: 10
      changed_when: false
`

	return os.WriteFile(filepath.Join(r.outputDir, "site.yml"), []byte(playbook), 0600)
}

