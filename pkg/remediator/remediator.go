func (r *Remediator) generateSTIGMapping(findings []models.Finding) error {
	var mapping strings.Builder

	mapping.WriteString("# STIG Control Mapping\n")
	mapping.WriteString("# Generated by StigKube\n")
	mapping.WriteString("# Maps STIG controls to remediation tasks\n\n")

	mapping.WriteString("controls:\n")
	for _, f := range findings {
		mapping.WriteString(fmt.Sprintf("  - id: %s\n", f.Control.ID))
		mapping.WriteString(fmt.Sprintf("    stig_id: %s\n", f.Control.STIGID))
		mapping.WriteString(fmt.Sprintf("    severity: %s\n", f.Control.CAT))
		mapping.WriteString(fmt.Sprintf("    title: \"%s\"\n", f.Control.Title))
		mapping.WriteString(fmt.Sprintf("    status: %s\n", f.Status))
		mapping.WriteString(fmt.Sprintf("    details: \"%s\"\n", strings.ReplaceAll(f.Details, "\"", "'")))
		if f.NodeName != "" {
			mapping.WriteString(fmt.Sprintf("    node: %s\n", f.NodeName))
		}
		mapping.WriteString("\n")
	}

	return os.WriteFile(filepath.Join(r.outputDir, "stig-mapping.yml"), []byte(mapping.String()), 0600)
}

// Helper functions

func (r *Remediator) getManifestPath(component string) string {
	switch r.deploymentMethod {
	case "kubeadm", "kubespray":
		return fmt.Sprintf("/etc/kubernetes/manifests/%s.yaml", component)
	case "rke2":
		return fmt.Sprintf("/var/lib/rancher/rke2/agent/pod-manifests/%s.yaml", component)
	case "k3s":
		return fmt.Sprintf("/var/lib/rancher/k3s/agent/pod-manifests/%s.yaml", component)
	default:
		return fmt.Sprintf("/etc/kubernetes/manifests/%s.yaml", component)
	}
}

func (r *Remediator) getKubeletConfigPath() string {
	switch r.deploymentMethod {
	case "kubeadm", "kubespray":
		return "/var/lib/kubelet/config.yaml"
	case "rke2":
		return "/var/lib/rancher/rke2/agent/kubelet.kubeconfig"
	case "k3s":
		return "/var/lib/rancher/k3s/agent/kubelet.kubeconfig"
	default:
		return "/var/lib/kubelet/config.yaml"
	}
}

func (r *Remediator) generateManifestPatchTask(f models.Finding, manifestPath string) string {
	// Extract flag name and value from expected
	flag, value := parseExpectedFlag(f.ExpectedValue)
	if flag == "" || value == "" {
		return fmt.Sprintf("# TODO: Manual remediation required for %s\n# Expected: %s\n# See STIG control %s for guidance\n\n", f.Control.ID, f.ExpectedValue, f.Control.STIGID)
	}

	return fmt.Sprintf(`- name: "Remediate %s - %s"
  lineinfile:
    path: %s
    regexp: '^\s*- %s'
    line: '    - %s=%s'
    insertafter: '^\s*- kube-'
    state: present
  register: manifest_changed
  notify: Wait for API server
  tags: [%s]

`, f.Control.ID, sanitizeTitle(f.Control.Title), manifestPath, flag, flag, value, f.Control.ID)
}

func (r *Remediator) generateKubeletConfigTask(f models.Finding, configPath string) string {
	// Extract setting name and value
	setting, value := parseExpectedYAML(f.ExpectedValue)
	if setting == "" || value == "" {
		return fmt.Sprintf("# TODO: Manual remediation required for %s\n# Expected: %s\n# See STIG control %s for guidance\n\n", f.Control.ID, f.ExpectedValue, f.Control.STIGID)
	}

	return fmt.Sprintf(`- name: "Remediate %s - %s"
  lineinfile:
    path: %s
    regexp: '^%s:'
    line: '%s: %s'
    state: present
  register: kubelet_config_changed
  tags: [%s]

`, f.Control.ID, sanitizeTitle(f.Control.Title), configPath, setting, setting, value, f.Control.ID)
}

