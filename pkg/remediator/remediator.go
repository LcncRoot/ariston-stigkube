func (r *Remediator) generateGeneralTasks(findings []models.Finding) error {
	var tasks strings.Builder

	tasks.WriteString("---\n")
	tasks.WriteString("# General Cluster STIG Remediation\n\n")

	for _, f := range findings {
		tasks.WriteString(fmt.Sprintf("# %s - %s\n", f.Control.ID, f.Control.Title))

		switch {
		case strings.Contains(f.Details, "NetworkPolicies"):
			tasks.WriteString(r.generateNetworkPolicyTask(f))
		case strings.Contains(f.Details, "Pod Security"):
			tasks.WriteString(r.generatePodSecurityTask(f))
		default:
			tasks.WriteString(fmt.Sprintf("# TODO: Manual remediation required for %s\n", f.Control.ID))
			tasks.WriteString(fmt.Sprintf("# Details: %s\n\n", f.Details))
		}
	}

	roleDir := filepath.Join(r.outputDir, "roles", "stig-remediation", "tasks")
	return os.WriteFile(filepath.Join(roleDir, "general.yml"), []byte(tasks.String()), 0600)
}

