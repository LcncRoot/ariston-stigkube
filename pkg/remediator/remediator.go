func (r *Remediator) generateMainTasks(findings []models.Finding) error {
	var tasks strings.Builder

	tasks.WriteString("---\n")
	tasks.WriteString("# STIG Remediation Tasks\n")
	tasks.WriteString("# Generated by StigKube\n")
	tasks.WriteString("# Deployment Method: " + r.deploymentMethod + "\n\n")

	// Group findings by component
	apiServerFindings := filterByComponent(findings, "api")
	controllerFindings := filterByComponent(findings, "controller")
	schedulerFindings := filterByComponent(findings, "scheduler")
	etcdFindings := filterByComponent(findings, "etcd")
	kubeletFindings := filterByComponent(findings, "kubelet")
	generalFindings := filterByComponent(findings, "general")

	// Include component-specific task files
	if len(apiServerFindings) > 0 {
		tasks.WriteString("- name: Include API Server remediation\n")
		tasks.WriteString("  include_tasks: apiserver.yml\n")
		tasks.WriteString("  tags: [apiserver]\n\n")
		if err := r.generateAPIServerTasks(apiServerFindings); err != nil {
			return err
		}
	}

	if len(controllerFindings) > 0 {
		tasks.WriteString("- name: Include Controller Manager remediation\n")
		tasks.WriteString("  include_tasks: controller-manager.yml\n")
		tasks.WriteString("  tags: [controller-manager]\n\n")
		if err := r.generateControllerManagerTasks(controllerFindings); err != nil {
			return err
		}
	}

	if len(schedulerFindings) > 0 {
		tasks.WriteString("- name: Include Scheduler remediation\n")
		tasks.WriteString("  include_tasks: scheduler.yml\n")
		tasks.WriteString("  tags: [scheduler]\n\n")
		if err := r.generateSchedulerTasks(schedulerFindings); err != nil {
			return err
		}
	}

	if len(etcdFindings) > 0 {
		tasks.WriteString("- name: Include etcd remediation\n")
		tasks.WriteString("  include_tasks: etcd.yml\n")
		tasks.WriteString("  tags: [etcd]\n\n")
		if err := r.generateEtcdTasks(etcdFindings); err != nil {
			return err
		}
	}

	if len(kubeletFindings) > 0 {
		tasks.WriteString("- name: Include Kubelet remediation\n")
		tasks.WriteString("  include_tasks: kubelet.yml\n")
		tasks.WriteString("  tags: [kubelet]\n\n")
		if err := r.generateKubeletTasks(kubeletFindings); err != nil {
			return err
		}
	}

	if len(generalFindings) > 0 {
		tasks.WriteString("- name: Include general cluster remediation\n")
		tasks.WriteString("  include_tasks: general.yml\n")
		tasks.WriteString("  tags: [general]\n\n")
		if err := r.generateGeneralTasks(generalFindings); err != nil {
			return err
		}
	}

	roleDir := filepath.Join(r.outputDir, "roles", "stig-remediation", "tasks")
	return os.WriteFile(filepath.Join(roleDir, "main.yml"), []byte(tasks.String()), 0600)
}

func (r *Remediator) generateAPIServerTasks(findings []models.Finding) error {
	var tasks strings.Builder

	tasks.WriteString("---\n")
	tasks.WriteString("# API Server STIG Remediation\n\n")

	manifestPath := r.getManifestPath("kube-apiserver")

	for _, f := range findings {
		tasks.WriteString(fmt.Sprintf("# %s - %s\n", f.Control.ID, f.Control.Title))
		tasks.WriteString(fmt.Sprintf("# Expected: %s\n", f.ExpectedValue))

		task := r.generateManifestPatchTask(f, manifestPath)
		tasks.WriteString(task)
		tasks.WriteString("\n")
	}

	roleDir := filepath.Join(r.outputDir, "roles", "stig-remediation", "tasks")
	return os.WriteFile(filepath.Join(roleDir, "apiserver.yml"), []byte(tasks.String()), 0600)
}

