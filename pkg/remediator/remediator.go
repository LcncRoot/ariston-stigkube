func filterByComponent(findings []models.Finding, component string) []models.Finding {
	var filtered []models.Finding
	for _, f := range findings {
		title := strings.ToLower(f.Control.Title)
		desc := strings.ToLower(f.Control.Description)
		details := strings.ToLower(f.Details)

		switch component {
		case "api":
			if strings.Contains(title, "api server") || strings.Contains(desc, "api server") ||
				strings.Contains(details, "apiserver") || strings.Contains(f.ExpectedValue, "--") {
				if !strings.Contains(title, "controller") && !strings.Contains(title, "scheduler") &&
					!strings.Contains(title, "etcd") && !strings.Contains(title, "kubelet") {
					filtered = append(filtered, f)
				}
			}
		case "controller":
			if strings.Contains(title, "controller") || strings.Contains(desc, "controller manager") {
				filtered = append(filtered, f)
			}
		case "scheduler":
			if strings.Contains(title, "scheduler") {
				filtered = append(filtered, f)
			}
		case "etcd":
			if strings.Contains(title, "etcd") || strings.Contains(desc, "etcd") {
				filtered = append(filtered, f)
			}
		case "kubelet":
			if strings.Contains(title, "kubelet") || strings.Contains(desc, "kubelet") ||
				strings.Contains(f.ExpectedValue, "readOnlyPort") ||
				strings.Contains(f.ExpectedValue, "tlsCertFile") {
				filtered = append(filtered, f)
			}
		case "general":
			if strings.Contains(details, "namespace") || strings.Contains(details, "networkpolic") ||
				strings.Contains(details, "pod security") {
				filtered = append(filtered, f)
			}
		}
	}
	return filtered
}

